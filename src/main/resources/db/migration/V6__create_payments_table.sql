CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    non_iata_id BIGINT NOT NULL,
    payment_date DATE NOT NULL,
    amount NUMERIC(18,2) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'ETB',
    receipt_number VARCHAR(100) NULL,
    payment_reference VARCHAR(150) NULL,
    notes TEXT NULL,
    receipt_object_key VARCHAR(500) NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'POSTED',
    created_by BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_payments_non_iata FOREIGN KEY (non_iata_id) REFERENCES non_iatas (id) ON DELETE RESTRICT,
    CONSTRAINT fk_payments_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_payments_amount CHECK (amount > 0),
    CONSTRAINT chk_payments_status CHECK (status IN ('POSTED', 'CANCELLED'))
);

CREATE INDEX idx_payments_non_iata_id ON payments (non_iata_id);
CREATE INDEX idx_payments_payment_date ON payments (payment_date);
CREATE INDEX idx_payments_receipt_number ON payments (receipt_number);
CREATE INDEX idx_payments_payment_reference ON payments (payment_reference);
CREATE INDEX idx_payments_status ON payments (status);
CREATE INDEX idx_payments_created_by ON payments (created_by);
