CREATE TABLE name_mappings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_name VARCHAR(255) NOT NULL,
    non_iata_id BIGINT NOT NULL,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_name_mappings_source_name UNIQUE (source_name),
    CONSTRAINT fk_name_mappings_non_iata FOREIGN KEY (non_iata_id) REFERENCES non_iatas (id) ON DELETE RESTRICT,
    CONSTRAINT fk_name_mappings_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT
);

CREATE INDEX idx_name_mappings_non_iata_id ON name_mappings (non_iata_id);
