CREATE TABLE import_batch_errors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_batch_id BIGINT NOT NULL,
    row_number INTEGER NOT NULL,
    ticket_number VARCHAR(100) NULL,
    source_agency_name VARCHAR(255) NULL,
    error_type VARCHAR(50) NOT NULL,
    message TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_import_batch_errors_batch FOREIGN KEY (import_batch_id) REFERENCES import_batches (id) ON DELETE CASCADE
);

CREATE INDEX idx_import_batch_errors_batch_id ON import_batch_errors (import_batch_id);

-- Enforce strict database-level duplicate immunity for sales transactions
ALTER TABLE sales_transactions
    ADD CONSTRAINT uk_sales_transactions_source_trans_key UNIQUE (source_transaction_key);
