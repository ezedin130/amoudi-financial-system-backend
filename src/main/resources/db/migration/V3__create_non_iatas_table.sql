CREATE TABLE non_iatas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(200) NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE',
    contact_name VARCHAR(200) NULL,
    phone VARCHAR(50) NULL,
    email VARCHAR(150) NULL,
    notes TEXT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_non_iatas_code UNIQUE (code),
    CONSTRAINT chk_non_iatas_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE INDEX idx_non_iatas_name ON non_iatas (name);
CREATE INDEX idx_non_iatas_status ON non_iatas (status);
